import { config } from '../config.js';

const UPDATED_AT = '09.05.2026';

function publicBaseUrl() {
  return String(config.PUBLIC_BASE_URL || 'https://webstudio.1true.ru').replace(/\/+$/, '');
}

function escapeHtml(value) {
  return String(value ?? '')
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}

function operatorInfo() {
  const ogrn = String(config.LEGAL_OPERATOR_OGRN || '').trim();
  const details = [
    config.LEGAL_OPERATOR_ADDRESS ? `Адрес: ${config.LEGAL_OPERATOR_ADDRESS}` : '',
    config.LEGAL_OPERATOR_INN ? `ИНН: ${config.LEGAL_OPERATOR_INN}` : '',
    ogrn && !/^0+$/.test(ogrn) ? `ОГРН/ОГРНИП: ${ogrn}` : '',
  ].filter(Boolean);

  return {
    name: config.LEGAL_OPERATOR_NAME || 'ИП Трушков Иван Алексеевич',
    email: config.LEGAL_OPERATOR_EMAIL || '1lab@1true.ru',
    details,
  };
}

export function legalUrl(pathname) {
  return `${publicBaseUrl()}${pathname}`;
}

export function legalLinks() {
  return {
    privacy: legalUrl('/privacy'),
    offer: legalUrl('/offer'),
    disclaimer: legalUrl('/disclaimer'),
    legal: legalUrl('/legal'),
  };
}

