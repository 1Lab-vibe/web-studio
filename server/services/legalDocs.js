function parseCookies(header = '') {
  return Object.fromEntries(
    String(header || '')
      .split(';')
      .map((part) => part.trim())
      .filter(Boolean)
      .map((part) => {
        const index = part.indexOf('=');
        if (index < 0) return [part, ''];
        return [part.slice(0, index), decodeURIComponent(part.slice(index + 1))];
      }),
  );
}

function consentSubjectFromRequest(req, res) {
  const cookies = parseCookies(req.headers.cookie || '');
  let subject = cookies.ws_consent_subject || '';
  if (!subject) {
    subject = `web:${cryptoRandomId()}`;
    res.cookie('ws_consent_subject', subject, {
      httpOnly: true,
      sameSite: 'lax',
      secure: Boolean(req.secure || req.get?.('x-forwarded-proto') === 'https'),
      maxAge: 365 * 24 * 60 * 60 * 1000,
    });
  }
  return subject;
}

function cryptoRandomId() {
  return randomUUID();
}

export function registerLegalRoutes(app, store) {
  app.get('/privacy', (req, res) => res.type('html').send(renderPage('privacy')));
  app.get('/personal-data-consent', (req, res) => res.type('html').send(renderPage('personalDataConsent')));
  app.get('/marketing-consent', (req, res) => res.type('html').send(renderPage('marketingConsent')));
  app.get('/offer', (req, res) => res.type('html').send(renderPage('offer')));
  app.get('/disclaimer', (req, res) => res.type('html').send(renderPage('disclaimer')));
  app.get('/legal', (req, res) => res.type('html').send(renderLegalIndex()));
  app.get('/api/consents/status', (req, res) => {
    const subjectKey = consentSubjectFromRequest(req, res);
    res.json({ ok: true, subjectKey, consents: store?.consentSummaryForSubject?.(subjectKey) || {} });
  });
  app.post('/api/consents', async (req, res) => {
    const type = String(req.body?.type || '');
    const decision = String(req.body?.decision || '');
    if (!['personal_data', 'marketing'].includes(type)) return res.status(400).json({ ok: false, error: 'Unknown consent type' });
    if (!['granted', 'declined', 'withdrawn'].includes(decision)) return res.status(400).json({ ok: false, error: 'Unknown consent decision' });
    const subjectKey = consentSubjectFromRequest(req, res);
    const record = await store.recordConsent({
      subjectKey,
      type,
      decision,
      documentVersion: req.body?.documentVersion || LEGAL_DOCUMENT_VERSION,
      documentUrl: req.body?.documentUrl || legalUrl(type === 'marketing' ? '/marketing-consent' : '/personal-data-consent'),
      source: 'web',
      actor: 'web-user',
      ip: req.ip,
      userAgent: req.get('user-agent') || '',
      evidenceText: decision === 'granted' ? 'User clicked consent button in web legal page' : 'User clicked decline/withdraw button in web legal page',
    });
    res.json({ ok: true, record, consents: store.consentSummaryForSubject(subjectKey) });
  });
}
