function renderSection(section) {
  const paragraphs = (section.paragraphs || []).map((item) => `<p>${escapeHtml(item)}</p>`).join('');
  const list = (section.list || []).filter(Boolean);
  const listHtml = list.length ? `<ul>${list.map((item) => `<li>${escapeHtml(item)}</li>`).join('')}</ul>` : '';
  return `<section><h2>${escapeHtml(section.title)}</h2>${paragraphs}${listHtml}</section>`;
}

